#!/usr/bin/env python3
"""Import Bible translations and create matched TSV corpora for MACULA scoring.

ASV downloader uses the public-domain ASV supplied by offlinebible.org, which
credits eBible.org as its text source. ESV and NASB MUST be independently
licensed/imported by the user; this script does NOT scrape those sources.

Only Python standard library required.
"""
from __future__ import annotations
import argparse
from collections import Counter
import csv
import hashlib
import io
import json
from pathlib import Path
import re
import sys
from urllib.request import Request, urlopen

from convert_bible_texts import BOOKS, ALIASES, ORDER, verse_sort, write_tsv

ASV_URL = 'https://offlinebible.org/downloads/asv.txt'
# eBible.org is the credited source and hosts the official archives:
ASV_OFFICIAL_SOURCE = 'https://ebible.org/find/show.php?id=eng-asv'
BOOK_NAMES = {code: aliases[-1] for code, *aliases in BOOKS}

ADDITIONAL_ALIASES = {
    'Psalm':'PSA','Psalms':'PSA','Song of Songs':'SNG','Song of Solomon':'SNG',
    'Song of Songs (Song of Solomon)':'SNG','Canticles':'SNG',
    'Revelation of John':'REV','The Revelation':'REV','The Acts':'ACT',
    '1 Thessalonians':'1TH','2 Thessalonians':'2TH',
    '1 Kings':'1KI','2 Kings':'2KI','1 Chronicles':'1CH','2 Chronicles':'2CH',
    '1 Samuel':'1SA','2 Samuel':'2SA','1 John':'1JN','2 John':'2JN',
    '3 John':'3JN','1 Peter':'1PE','2 Peter':'2PE',
    'Philemon':'PHM','Jonah':'JON','Ezekiel':'EZK',
    '1 Corinthians':'1CO','2 Corinthians':'2CO','1 Timothy':'1TI','2 Timothy':'2TI',
    'Philippians':'PHP','Titus':'TIT','2 Thess.':'2TH',
}
ALIASES2 = {**ALIASES, **{code: code for code, *_ in BOOKS}, **ADDITIONAL_ALIASES}
NORMALIZED = {re.sub(r'[^a-z0-9]','',a.lower()): code for a,code in ALIASES2.items()}
# Allow names such as '1st John' and 'II Kings'.
for p, q in [('1st','1'),('2nd','2'),('3rd','3'),('I','1'),('II','2'),('III','3')]:
    for name,code in list(ALIASES2.items()):
        if name.startswith(q+' '):
            NORMALIZED[re.sub(r'[^a-z0-9]','',(p+' '+name[2:]).lower())] = code

VERSE_LINE = re.compile(r'^\s*(.+?)\s+(\d+):(\d+)(?:\s+|\s*[\u2014-]\s*)(.+?)\s*$')
CANONICAL = re.compile(r'^([A-Za-z0-9]{3})\.(\d+)\.(\d+)$')


def normalize_verse(raw: str) -> str:
    raw = raw.strip()
    m=CANONICAL.fullmatch(raw)
    if m:
        book, chapter, verse=m.groups()
        if book.upper() not in ORDER: raise ValueError(f'Unrecognized book code {book}')
        return f'{book.upper()}.{int(chapter)}.{int(verse)}'
    m=re.fullmatch(r'\s*(.+?)\s+(\d+):(\d+)\s*',raw)
    if m:
        b,c,v=m.groups()
        code=NORMALIZED.get(re.sub(r'[^a-z0-9]','',b.lower()))
        if code is None: raise ValueError(f'Unrecognized book name {b!r}')
        return f'{code}.{int(c)}.{int(v)}'
    raise ValueError(f'Unrecognized verse reference {raw!r}')


def parse_lines(text: str, *, strict: bool=False) -> dict[str,str]:
    verses={}
    unknown=[]
    for lineno,line in enumerate(text.splitlines(),1):
        line=line.strip().lstrip('\ufeff')
        if not line or line.startswith('#'): continue
        if line.lower().startswith(('american standard version','public domain','source:','copyright','translation:','generated by')): continue
        m=VERSE_LINE.fullmatch(line)
        if m is None:
            if strict: unknown.append((lineno,line[:100]))
            continue
        book,c,v,content=m.groups()
        code=NORMALIZED.get(re.sub(r'[^a-z0-9]','',book.lower()))
        if not code:
            unknown.append((lineno,line[:100]))
            continue
        ref=f'{code}.{int(c)}.{int(v)}'
        if ref in verses:
            raise ValueError(f'Duplicate verse {ref} at line {lineno}')
        # Preserve wording, punctuation, bracketed supplied words.
        content=content.strip()
        if content: verses[ref]=content
    if unknown:
        raise ValueError(f'Unrecognized verse lines ({len(unknown)}), e.g. {unknown[:5]}')
    if not verses:
        raise ValueError('No Bible verses detected. Expected Book chapter:verse text.')
    return verses


def parse_delimited(text:str,delimiter:str) -> dict[str,str]:
    reader=csv.DictReader(io.StringIO(text),delimiter=delimiter)
    if not reader.fieldnames: raise ValueError('No column headers')
    names={name.strip().lower():name for name in reader.fieldnames}
    if not {'verse','text'}.issubset(names): raise ValueError(f'Expected verse and text columns; got {reader.fieldnames}')
    out={}
    for index,row in enumerate(reader,2):
        raw=(row.get(names['verse']) or '').strip()
        content=(row.get(names['text']) or '').strip()
        if not raw or not content: continue
        ref=normalize_verse(raw)
        if ref in out: raise ValueError(f'Duplicate verse {ref} at row {index}')
        out[ref]=content
    if not out: raise ValueError('No Bible verses found')
    return out


def parse_json(text:str)->dict[str,str]:
    obj=json.loads(text)
    if isinstance(obj,list):
        if not all(isinstance(item,dict) for item in obj):
            raise ValueError('JSON lists must contain {verse,text} objects')
        rows=[(item['verse'],item['text']) for item in obj]
    elif isinstance(obj,dict):
        if all(isinstance(v,str) for v in obj.values()):
            rows=list(obj.items())
        else:
            raise ValueError('JSON object must map verse references to strings; otherwise use verse/text objects')
    else: raise ValueError('Expected JSON object or list of verse/text objects')
    out={}
    for raw,content in rows:
        if not content: continue
        ref=normalize_verse(str(raw))
        if ref in out: raise ValueError('Duplicate '+ref)
        out[ref]=str(content).strip()
    if not out: raise ValueError('No verses in JSON')
    return out


def parse_source(path:Path, fmt='auto') -> dict[str,str]:
    text=path.read_text(encoding='utf-8-sig')
    if fmt=='auto':
        suffix=path.suffix.lower()
        if suffix=='.json': fmt='json'
        elif suffix=='.csv': fmt='csv'
        elif suffix=='.tsv': fmt='tsv'
        elif '\t' in text.splitlines()[0] and text.lstrip('\ufeff').splitlines()[0].lower().startswith('verse'):
            fmt='tsv'
        else: fmt='txt'
    if fmt=='txt': return parse_lines(text)
    if fmt=='tsv': return parse_delimited(text,'\t')
    if fmt=='csv': return parse_delimited(text,',')
    if fmt=='json': return parse_json(text)
    raise ValueError(f'Unsupported format {fmt}')


def audit_verses(verses, name, minimum):
    count=len(verses)
    books=set(v.split('.',1)[0] for v in verses)
    print(f'{name}: {count:,} nonempty verses; {len(books)} books')
    if count < minimum:
        raise ValueError(f'{name} has only {count:,} verses (<{minimum:,}); source may be incomplete. '
                         'For intentionally partial input use --min-verses 1.')
    if minimum>=30000 and len(books)!=66:
        raise ValueError(f'{name} appears incomplete: found {len(books)} books, expected 66')


def cmd_download_asv(args):
    dest=Path(args.out)
    raw=Path(args.raw)
    if args.local:
        raw=Path(args.local)
        if not raw.is_file(): raise ValueError(f'Local source file not found: {raw}')
    else:
        raw.parent.mkdir(parents=True, exist_ok=True)
        print(f'Downloading public-domain ASV from {args.url}')
        with urlopen(Request(args.url,headers={'User-Agent':'Bible-Study-Research-Toolkit/4.0'}),timeout=120) as response:
            data=response.read()
        if len(data)<100_000: raise ValueError(f'ASV download unexpectedly small: {len(data)} bytes')
        raw.write_bytes(data)
    verses=parse_source(raw, 'txt')
    audit_verses(verses,'ASV',30000)
    n=write_tsv(dest,verses)
    meta={'translation':'ASV','edition':'1901','source_url':args.url if not args.local else 'user supplied local ASV',
          'origin':ASV_OFFICIAL_SOURCE,'source_sha256':hashlib.sha256(raw.read_bytes()).hexdigest(),
          'verse_count':n,'format':'TSV', 'license':'Public domain (US)'}
    dest.with_suffix('.metadata.json').write_text(json.dumps(meta,indent=2)+'\n',encoding='utf-8')
    print(f'Saved {n:,} verses: {dest}')
    return verses


def cmd_import(args):
    name=args.name.upper()
    if not re.fullmatch(r'[A-Z0-9_-]{2,20}',name): raise ValueError('Translation name must be 2-20 uppercase letters, digits, _ or -')
    source=Path(args.input)
    if not source.exists(): raise ValueError(f'Input file not found: {source}')
    verses=parse_source(source,args.format)
    audit_verses(verses,name,args.min_verses)
    out=Path(args.out or f'translations/full/{name}.tsv')
    n=write_tsv(out,verses)
    meta={'translation':name,'edition':args.edition or 'unspecified',
          'source':'user supplied authorized text',
          'source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),
          'verse_count':n,'format':'TSV','usage':"Comply with copyright owner's terms; do not redistribute"}
    out.with_suffix('.metadata.json').write_text(json.dumps(meta,indent=2)+'\n',encoding='utf-8')
    print(f'Saved {n:,} verses: {out}')
    print('This program only imports data you have the right to use. No downloads from ESV/NASB sites are performed.')
    return verses


def find_file(base:Path,name:str):
    for candidate in [base/'translations'/'full'/f'{name}.tsv',base/'translations'/'common'/f'{name}.tsv',base/'translations'/f'{name}.tsv']:
        if candidate.is_file(): return candidate
    raise FileNotFoundError(f'Missing {name} translation TSV in translations/full or translations/common. Import it first.')


def cmd_common(args):
    base=Path(args.base)
    versions=[v.upper() for v in args.versions]
    if len(set(versions)) !=len(versions) or len(versions)<2:
        raise ValueError('At least two distinct version names required')
    corpus={}
    paths={}
    for v in versions:
        path=find_file(base,v)
        paths[v]=path
        corpus[v]=parse_source(path,'tsv')
    shared=set.intersection(*(set(d) for d in corpus.values()))
    if not shared: raise ValueError('No shared verse references')
    out=Path(args.outdir or base/'translations'/'comparison'/('_'.join(versions)))
    out.mkdir(parents=True,exist_ok=True)
    union=set.union(*(set(d) for d in corpus.values()))
    report=[f'# Matched corpus: {", ".join(versions)}','',f'Common verse IDs: **{len(shared):,}**','',
      '| Translation | Input verses | Shared verses | Excluded from comparison | Missing vs union |','|---|---:|---:|---:|---:|']
    for v in versions:
        data=corpus[v]
        file=out/f'{v}.tsv'
        write_tsv(file,data,shared)
        excluded=len(set(data)-shared)
        missing=len(union-set(data))
        report.append(f'| {v} | {len(data):,} | {len(shared):,} | {excluded:,} | {missing:,} |')
        print(f'{v}: {len(data):,} input, {len(shared):,} common -> {file}')
    report += ['','The matched set compares identical **verse IDs**, not necessarily identical Hebrew/Greek versification.',
               'MACULA Hebrew and English verse numbering differ in several passages, so the MACULA pipeline may report additional unmatched references.',
               '', 'Source files:', *[f'- {v}: `{paths[v]}`' for v in versions], '']
    (out/'COVERAGE.md').write_text('\n'.join(report),encoding='utf-8')
    print(f'Common verse set: {len(shared):,}; report: {out}/COVERAGE.md')
    return out


def main():
    p=argparse.ArgumentParser(description=__doc__)
    sub=p.add_subparsers(dest='command',required=True)
    a=sub.add_parser('download-asv',help='Fetch public-domain ASV and create verse TSV')
    a.add_argument('--url',default=ASV_URL)
    a.add_argument('--local',help='Parse already downloaded ASV plain text instead of fetching')
    a.add_argument('--raw',default='data/asv/asv.txt')
    a.add_argument('--out',default='translations/full/ASV.tsv')
    a.set_defaults(func=cmd_download_asv)
    a=sub.add_parser('import',help='Convert an authorized ESV/NASB or other text into verse TSV')
    a.add_argument('--name',required=True)
    a.add_argument('--input',required=True)
    a.add_argument('--format',choices=['auto','txt','tsv','csv','json'],default='auto')
    a.add_argument('--min-verses',type=int,default=30000)
    a.add_argument('--edition',help='Record edition for reproducibility (e.g., NASB 1995 or 2020)')
    a.add_argument('--out')
    a.set_defaults(func=cmd_import)
    a=sub.add_parser('common',help='Create matched verse set across existing translations')
    a.add_argument('--versions',nargs='+',required=True)
    a.add_argument('--base',default='.')
    a.add_argument('--outdir')
    a.set_defaults(func=cmd_common)
    args=p.parse_args()
    try: args.func(args)
    except (ValueError,FileNotFoundError,OSError) as e:
        p.exit(1,f'ERROR: {e}\n')

if __name__=='__main__': main()
