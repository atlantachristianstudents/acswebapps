const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../app.js'), 'utf8');
const context = vm.createContext({history: []});
vm.runInContext(source.slice(source.indexOf('function historyResultDate('), source.indexOf('function historyWithinDateRange(')), context);
const run = code => vm.runInContext(code, context);
assert.equal(run('historyJoinedDate()'), null);
assert(run('profileJoinedLabel()').includes('first typing test'));
context.history = [{date:'2026-11-08T12:00:00Z'}, {date:'invalid'}, {date:'2026-01-02'}, {date:'2026-06-01T10:00:00Z'}];
assert.equal(run('historyJoinedDate().getFullYear()'), 2026);
assert.equal(run('historyJoinedDate().getMonth()'), 0);
assert.equal(run('historyJoinedDate().getDate()'), 2);
context.history.push({date:'2025-03-04'});
assert.equal(run('historyJoinedDate().getFullYear()'), 2025, 'older imported history moves joined date earlier');
context.history.push({date:'2027-01-01'});
assert.equal(run('historyJoinedDate().getFullYear()'), 2025, 'new results preserve joined date');
context.history = [{date:'invalid'}];
assert.equal(run('historyJoinedDate()'), null);
context.history = [];
assert.equal(run('historyJoinedDate()'), null, 'clearing data resets date joined');
console.log('Date joined checks passed: earliest result, unordered history, legacy dates, invalid dates, imports, new results, clear data.');
